#ifndef GENETIC_ALGORITHM_H_
#define GENETIC_ALGORITHM_H_

#include <random>
#include <vector>
#include <utility>
#include "instance.h"

/**
 * @brief Implements the Genetic Algorithm for PFSP
 */
class GeneticAlgorithm {
    
  public:

    /**
     * @brief Constructs a Genetic Algorithm.
     *
     * @param population_size Number of individuals in the population.
     * @param pc Crossover probability.
     * @param pm Mutation probability.
     * @param tournament_size Number of individuals participating in tournament selection.
     * @param seed Seed used by the pseudo-random number generator.
     */
    GeneticAlgorithm(int population_size, double pc, double pm, 
      int tournament_size, unsigned int seed, const std::string& crossover_type = "OX");
    

    /**
     * @brief execution of the Genetic Algorithm for PFSP instances
     * Generation of an initial population and subsequent evolution 
     * until maximum number of makespan evaluations
     * @param instance PFSP instance to solve
     * @param evaluation Max number of evaluations
     */
    void run(const Instance& instance, int evaluations);

    /**
     * @brief Returns the best permutation found
     * @return Best job permutation
     */
    const std::vector<int>& getBestPermutation() const {
      return best_permutation_;
    }

    /**
     * @brief Returns the makespan of the best solution found
     * @return Best makespan
     */
    int getBestMakespan() const {
      return best_makespan_;
    }

    /**
     * @brief Returns the convergence history of the algorithm
     * 
     * @return Convergence history
     */
    const std::vector<std::pair<int, int>>& getConvergence() const {
      return convergence_;
    }


  private:
    int population_size_;
    double pc_;
    double pm_;
    int tournament_size_;
    std::mt19937 generator_;
    const std::string& crossover_type_;
    
    std::vector<std::pair<int, int>> convergence_;

    std::vector<int> best_permutation_;
    int best_makespan_;


    std::vector<std::pair<std::vector<int>, int>> population_;


    /**
    * @brief Selects an individual using tournament selection.
    *
    * Randomly selects (tournament_size_) individuals and returns the index of
    * the one with the lowest makespan.
    *
    * @return Index of the selected individual.
    */
    int tournamentSelection();

    /**
    * @brief Generates a child using Order Crossover (OX).
    *
    * A segment from the first parent is copied to the child and the remaining
    * jobs are inserted following their relative order in the second parent.
    *
    * @param parent1 First parent.
    * @param parent2 Second parent.
    * @return Child permutation generated by OX.
    */
    std::vector<int> orderCrossover(const std::vector<int>& parent1, const std::vector<int>& parent2);

    std::vector<int> partiallyMappedCrossover(const std::vector<int>& parent1, const std::vector<int>& parent2, int cut1, int cut2);


    /**
    * @brief Applies swap mutation to an individual.
    *
    * Two different positions are selected randomly and their jobs are exchanged.
    *
    * @param individual Permutation to mutate.
    */
    void swapMutation(std::vector<int>& individual);

    /**
    * @brief Applies insertion mutation to an individual.
    *
    * A job is removed from one position and inserted into another randomly selected position.
    *
    * @param individual Permutation to mutate.
    */
    void insertionMutation(std::vector<int>& individual);

    /**
    * @brief Checks whether a permutation is valid.
    *
    * A valid PFSP permutation must contain every job exactly once.
    *
    * @param permutation Permutation to validate.
    * @param jobs Number of jobs expected in the permutation.
    * @return true if the permutation is valid, false otherwise.
    */
    bool isValidPermutation(const std::vector<int>& permutation, int jobs) const;

};
#endif